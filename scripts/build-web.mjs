/**
 * Builds the iPhone / browser home-screen version of the app into docs/app,
 * which GitHub Pages serves at https://<user>.github.io/stock-qr-inventory-app/app/
 *
 *   npm run build:web
 *
 * Steps: expo export (web) → add iOS home-screen tags, web manifest and an offline
 * service worker → copy into docs/app.
 */
import { execSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'web-build');
const target = path.join(root, 'docs', 'app');
const appJson = JSON.parse(fs.readFileSync(path.join(root, 'app.json'), 'utf8')).expo;
const base = `${appJson.experiments?.baseUrl ?? ''}/`.replace(/\/+$/, '/');

console.log('› Exporting web bundle…');
fs.rmSync(out, { recursive: true, force: true });
execSync(`npx expo export --platform web --output-dir web-build`, { cwd: root, stdio: 'inherit' });

// ---- move fonts out of "node_modules" -------------------------------------------
// Expo puts icon fonts under assets/node_modules/…, but .gitignore skips every
// node_modules folder, so they would never reach GitHub Pages. Move them to
// assets/vendor/… and keep only the icon font the app actually uses.
{
  const from = path.join(out, 'assets', 'node_modules');
  const to = path.join(out, 'assets', 'vendor');
  if (fs.existsSync(from)) {
    fs.renameSync(from, to);
    const walk = (dir) =>
      fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]
      );
    for (const f of walk(to)) {
      if (f.endsWith('.ttf') && !path.basename(f).startsWith('Ionicons')) fs.rmSync(f);
    }
    for (const f of walk(path.join(out, '_expo'))) {
      if (!f.endsWith('.js')) continue;
      const js = fs.readFileSync(f, 'utf8');
      if (js.includes('/assets/node_modules/')) fs.writeFileSync(f, js.split('/assets/node_modules/').join('/assets/vendor/'));
    }
  }
}

// ---- icons -----------------------------------------------------------------
const icons = ['apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'favicon.png'];
fs.mkdirSync(path.join(out, 'icons'), { recursive: true });
for (const f of icons) fs.copyFileSync(path.join(root, 'assets', f), path.join(out, 'icons', f));

// ---- manifest ----------------------------------------------------------------
const manifest = {
  name: 'Stock & QR Inventory',
  short_name: 'Stock QR',
  description: 'Scan, sell and restock with QR codes. Works offline.',
  start_url: base,
  scope: base,
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#F2F2F7',
  theme_color: '#F2F2F7',
  icons: [
    { src: `${base}icons/icon-192.png`, sizes: '192x192', type: 'image/png' },
    { src: `${base}icons/icon-512.png`, sizes: '512x512', type: 'image/png' },
    { src: `${base}icons/icon-maskable-512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

// ---- service worker (offline) --------------------------------------------------
function listFiles(dir, prefix = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listFiles(path.join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]
  );
}
const files = listFiles(out).filter((f) => !f.endsWith('.map') && f !== 'sw.js');
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(out, f)));
const version = hash.digest('hex').slice(0, 12);
// Only Ionicons is used; other icon fonts are cached later only if ever requested.
const precache = [
  base,
  ...files
    .filter((f) => f !== 'index.html' && f !== 'metadata.json')
    .filter((f) => !f.endsWith('.ttf') || f.includes('Ionicons'))
    .map((f) => `${base}${f}`),
];

const sw = `/* Generated by scripts/build-web.mjs — offline support for the home-screen app */
const CACHE = 'stockqr-${version}';
const PRECACHE = ${JSON.stringify(precache)};
// QR decoder that the camera scanner loads on the web
const RUNTIME_HOSTS = ['cdn.jsdelivr.net'];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('stockqr-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // The app page: network first so updates arrive, cached copy when offline
  if (req.mode === 'navigate' && url.origin === location.origin) {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('${base}', copy));
          return res;
        })
        .catch(() => caches.match('${base}'))
    );
    return;
  }

  // App files and the QR decoder: cache first
  if ((url.origin === location.origin && url.pathname.startsWith('${base}')) || RUNTIME_HOSTS.includes(url.hostname)) {
    e.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          })
      )
    );
  }
  // Everything else (sync relay, update checks) goes straight to the network.
});
`;
fs.writeFileSync(path.join(out, 'sw.js'), sw);

// ---- index.html: iOS home-screen tags -------------------------------------------
const indexPath = path.join(out, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const head = `
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="apple-mobile-web-app-title" content="Stock QR" />
    <meta name="application-name" content="Stock QR" />
    <meta name="description" content="Scan, sell and restock with QR codes. Works offline." />
    <meta name="format-detection" content="telephone=no" />
    <meta name="theme-color" content="#F2F2F7" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#000000" media="(prefers-color-scheme: dark)" />
    <link rel="manifest" href="${base}manifest.webmanifest" />
    <link rel="apple-touch-icon" href="${base}icons/apple-touch-icon.png" />
    <link rel="icon" type="image/png" href="${base}icons/favicon.png" />
    <style>
      html, body { background: #F2F2F7; overscroll-behavior: none; -webkit-tap-highlight-color: transparent; }
      @media (prefers-color-scheme: dark) { html, body { background: #000; } }
      body { -webkit-user-select: none; user-select: none; }
      input, textarea { -webkit-user-select: text; user-select: text; font-size: 17px; }
    </style>
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('${base}sw.js', { scope: '${base}' }).catch(function () {});
        });
      }
    </script>
`;
html = html
  .replace(/<meta name="viewport"[^>]*>/, '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />')
  .replace(/<title>[^<]*<\/title>/, '<title>Stock QR</title>')
  .replace('</head>', `${head}</head>`);
if (!html.includes('viewport-fit=cover')) {
  html = html.replace('<head>', '<head>\n    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />');
}
fs.writeFileSync(indexPath, html);

// ---- safety: nothing may live under a node_modules path (it would not be committed) ----
{
  const bad = listFiles(out).filter((f) => f.split('/').includes('node_modules'));
  if (bad.length) throw new Error(`Build output still has node_modules paths:\n${bad.join('\n')}`);
  const fonts = listFiles(out).filter((f) => f.endsWith('.ttf'));
  if (!fonts.some((f) => f.includes('Ionicons'))) throw new Error('Ionicons font missing from the web build.');
}

// ---- publish into docs/app ----------------------------------------------------------
fs.rmSync(target, { recursive: true, force: true });
fs.cpSync(out, target, { recursive: true });
// GitHub Pages hides folders starting with _ (like _expo) unless the site root has .nojekyll
fs.writeFileSync(path.join(root, 'docs', '.nojekyll'), '');
// ---- every published file must be committable (a .gitignore rule once hid the icon font) ----
{
  const published = listFiles(target).map((f) => `docs/app/${f}`);
  let ignored = '';
  try {
    ignored = execSync('git check-ignore --stdin', { cwd: root, input: published.join('\n') }).toString().trim();
  } catch {
    ignored = ''; // exit code 1 = nothing ignored
  }
  if (ignored) throw new Error(`These web files are git-ignored and would not be published:\n${ignored}`);
}
console.log(`✓ Web app built into docs/app (cache ${version}, ${files.length} files)`);
